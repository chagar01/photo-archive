#!/usr/bin/env bash
# Make Immich's server and machine-learning containers run as you instead of root, so the
# .xmp sidecars Immich writes stay editable by the pipeline and a compromised Immich
# can't act as root on your photos. Also hands back data files a sudo-run install left
# owned by root (the database folder keeps the owner Docker gave it).
#
#   scripts/immich-as-user.sh [DATA_FOLDER] [--no-start]
#
# DATA_FOLDER defaults to BASE_DIR from ~/.config/photo-archive/config.env. Run as your
# normal user; it asks for sudo. install.sh calls it with --no-start. Safe to re-run.
set -euo pipefail

warn() { printf '\033[33m%s\033[0m\n' "$*"; }
die()  { printf '\033[31mError: %s\033[0m\n' "$*" >&2; exit 1; }

[[ $EUID -ne 0 ]] || die "run as your normal user, not with sudo (it asks for sudo when needed)"
BASE_DIR=""; start=1
for a in "$@"; do
    case "$a" in
        --no-start) start=0 ;;
        -*) die "usage: $0 [DATA_FOLDER] [--no-start]" ;;
        *) BASE_DIR="$a" ;;
    esac
done
CONFIG_FILE="$HOME/.config/photo-archive/config.env"
if [[ -z "$BASE_DIR" && -f "$CONFIG_FILE" ]]; then
    BASE_DIR="$(bash -c 'source "$1"; printf %s "$BASE_DIR"' _ "$CONFIG_FILE")"
fi
[[ -n "$BASE_DIR" ]] || die "usage: $0 DATA_FOLDER   (the folder holding Library/ and immich/)"
# Absolute: Docker reads relative paths in the override from the immich/ folder.
BASE_DIR="$(realpath -m -- "${BASE_DIR/#\~/$HOME}")"
IMMICH_DIR="$BASE_DIR/immich"
sudo test -f "$IMMICH_DIR/docker-compose.yml" || die "no Immich setup in $IMMICH_DIR"
sudo test -d "$BASE_DIR/Library" || die "no Library folder in $BASE_DIR"
uid="$(id -u)"; gid="$(id -g)"
compose() { (cd "$IMMICH_DIR" && sudo docker compose "$@"); }

if (( start )); then
    echo "Stopping Immich server and machine learning..."
    compose stop immich-server immich-machine-learning >/dev/null
fi

# Everything except the database folder (owned by the postgres user inside its container).
sudo chown "$USER": "$BASE_DIR" "$IMMICH_DIR"
sudo mkdir -p "$IMMICH_DIR"/{upload,ml-cache/{cache,home-cache,home-config}}
for p in "$BASE_DIR"/* "$IMMICH_DIR"/* "$IMMICH_DIR"/.env; do
    [[ -e "$p" && "$p" != "$IMMICH_DIR" && "$p" != "$IMMICH_DIR/postgres" ]] || continue
    if [[ -n "$(sudo find "$p" ! -user "$USER" -print -quit)" ]]; then
        echo "Giving $p to $USER..."
        sudo chown -R "$USER": "$p"
    fi
done
chmod 600 "$IMMICH_DIR/.env"

# Models used to live in the Docker volume <project>_model-cache: move them over rather
# than download again. The emptied volume is removed once Immich is confirmed working.
project="$(sudo sed -n 's/^name:[[:space:]]*//p' "$IMMICH_DIR/docker-compose.yml" | tr -d "\"'")"
old_vol="${project:-$(basename "$IMMICH_DIR")}_model-cache"
old_dir="$(sudo docker volume inspect -f '{{.Mountpoint}}' "$old_vol" 2>/dev/null || true)"
if [[ -n "$old_dir" && -z "$(ls -A "$IMMICH_DIR/ml-cache/cache")" ]] && sudo test -n "$(sudo ls -A "$old_dir")"; then
    echo "Moving downloaded models from Docker volume $old_vol to $IMMICH_DIR/ml-cache/cache..."
    sudo cp -a "$old_dir/." "$IMMICH_DIR/ml-cache/cache/"
    sudo chown -R "$USER": "$IMMICH_DIR/ml-cache/cache"
fi

# Library is writable so Immich can save your edits (dates, descriptions) into
# <photo>.xmp sidecars; read-only makes Immich silently revert them.
cat >"$IMMICH_DIR/docker-compose.override.yml" <<EOF
# Generated by photo-archive (scripts/immich-as-user.sh) -- edits will be overwritten.
services:
  immich-server:
    user: "$uid:$gid"
    volumes:
      - $BASE_DIR/Library:/mnt/library
  immich-machine-learning:
    user: "$uid:$gid"
    volumes:
      - $IMMICH_DIR/ml-cache/cache:/cache
      - $IMMICH_DIR/ml-cache/home-cache:/.cache
      - $IMMICH_DIR/ml-cache/home-config:/.config
EOF
echo "Wrote $IMMICH_DIR/docker-compose.override.yml (Immich runs as uid $uid)."

# A sudo-run install also put the pipeline's config and cron job in root's account.
if sudo test -f /root/.config/photo-archive/config.env || sudo crontab -l -u root 2>/dev/null | grep -q photo-archive; then
    warn "photo-archive was also installed for root (sudo). Re-run install.sh as $USER, then"
    warn "remove root's copy: sudo crontab -e (delete the photo-archive line)."
fi

(( start )) || exit 0
echo "Starting Immich..."
compose up -d >/dev/null
port="$(sudo grep -oE "^\s*- '?[0-9]+:2283" "$IMMICH_DIR/docker-compose.yml" | grep -oE '[0-9]+' | head -n 1)"
for _ in $(seq 1 60); do curl -fs "http://localhost:${port:-2283}/api/server/ping" >/dev/null && break; sleep 5; done
curl -fs "http://localhost:${port:-2283}/api/server/ping" >/dev/null \
    || die "Immich didn't come back; check: cd $IMMICH_DIR && sudo docker compose logs immich-server"
for c in immich-server immich-machine-learning; do
    got="$(compose exec -T "$c" id -u)"
    [[ "$got" == "$uid" ]] || die "$c runs as uid $got, expected $uid"
done
mounted="$(sudo docker inspect "$(compose ps -q immich-server)" \
    -f '{{range .Mounts}}{{if eq .Destination "/mnt/library"}}{{.Source}}{{end}}{{end}}')"
[[ "$mounted" == "$BASE_DIR/Library" ]] || die "Immich mounts '$mounted' as the Library, expected $BASE_DIR/Library"
compose exec -T immich-server sh -c 't=/mnt/library/.write-test; touch $t && rm $t' \
    || die "Immich can't write to $BASE_DIR/Library"
# Photos Immich marked offline (and trashed) while it couldn't see them come back on a scan.
key_file="$BASE_DIR/state/immich_api_key"
if [[ -s "$key_file" ]]; then
    api() { curl -fsS -H "x-api-key: $(cat "$key_file")" -H 'content-type: application/json' "$@"; }
    lib_id="$(api "http://localhost:${port:-2283}/api/libraries" | python3 -c '
import json, sys
print(next((l["id"] for l in json.load(sys.stdin) if "/mnt/library" in l["importPaths"]), ""))' || true)"
    if [[ -n "$lib_id" ]] && api -X POST "http://localhost:${port:-2283}/api/libraries/$lib_id/scan" >/dev/null; then
        echo "Asked Immich to rescan the Library (photos marked offline come back within minutes)."
    else
        warn "Couldn't start a Library scan; in Immich: Administration > External Libraries > Scan."
    fi
fi
if [[ -n "$old_dir" ]]; then
    # Docker refuses while any container still mounts it, so this can't pull models from
    # under Immich. The base compose file still declares it; an empty one may reappear.
    sudo docker volume rm "$old_vol" >/dev/null 2>&1 \
        && echo "Removed the old model volume $old_vol." \
        || warn "Couldn't remove the old model volume; later: sudo docker volume rm $old_vol"
fi
echo "Done: Immich is up and runs as $USER (uid $uid)."
